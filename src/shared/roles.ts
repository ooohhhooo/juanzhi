把学校的英语考试卷（PDF、照片、Word）交给它，它会：读出每道题、标上“考什么”（知识点）和难易程度，再按学年、年级统计出**今年考什么、哪里容易错、和去年比有什么变化**，最后写成给老板、家长、老师看的报告。

