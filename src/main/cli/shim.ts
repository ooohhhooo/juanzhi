/**
 * 短命令 `juanzhi` 的安装（M7）：Mac 写 shell 包装脚本，Windows 写 juanzhi.cmd 并把目录加进用户级 PATH（不需要管理员权限）。
 * 脚本内容是纯函数（单测核对）；写文件 / 改 PATH 的部分把环境（平台、家目录、PowerShell 执行器）作为参数传入，单测可以替换。
 * 安全规则：已有同名文件时，只有它带「JUANZHI-SHIM」标记（我们自己写的）才替换；符号链接、别人的文件一律拒绝；写入用临时文件 + 改名。不依赖 electron。
 */
import fs from 'node:fs'
import path from 'node:path'
import { execFile } from 'node:child_process'
import { asciiJson } from './args.ts'

/** 包装脚本里的标记：安装时靠它判断「这个文件是不是我们以前写的」 */
export const SHIM_MARK = 'JUANZHI-SHIM v2'

/** 单引号包起来的 shell 字符串（路径里有单引号也安全） */
export const shQuote = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`

/** Mac / Linux：~/.local/bin/juanzhi */
export function buildShellShim(exePath: string): string {
  return [
    '#!/bin/sh',
    `# ${SHIM_MARK}：由「卷知」生成（设置 → 管理员设置 → 安装命令行工具）。卷知被移动或卸载后，请重新安装命令行工具。`,
    `exec ${shQuote(exePath)} cli "$@"`,
    ''
  ].join('\n')
}

/** 包装脚本自己报错时输出的 JSON（纯 ASCII，和命令行本身的输出一样不怕控制台编码） */
const shimError = (message: string): string => asciiJson(JSON.stringify({ ok: false, code: 'internal', message, exit: 1 }))

/**
 * Windows：juanzhi.cmd。
 * Electron 是 GUI 子系统程序：cmd / PowerShell 直接运行它既不等它结束，也拿不到 stdout 和退出码。
 * 所以这里用 `start /wait` 同步等待，让程序把 JSON 结果写到临时文件（环境变量 JUANZHI_RESULT_FILE，同时写一个 .exit 文件放退出码），再 `type` 到 stdout，并返回退出码。
 * 退出码以 .exit 文件为准（免安装版的外层启动器不传递退出码、或程序在写完结果之后崩溃时，调用方仍然拿到正确的码）。
 * 脚本里除了 exe 路径（可能含中文用户名）全是 ASCII，所以 `goto` 在任何代码页下都不会跳错；程序输出的 JSON 也是纯 ASCII（非 ASCII 字符写成 \uXXXX）。
 * 路径里的 % 写成 %%；显式关掉延迟展开（路径或参数里的 ! 不会被吃掉）。
 */
export function buildCmdShim(exePath: string): string {
  const exe = exePath.replace(/%/g, '%%')
  const lines = [
    '@echo off',
    'setlocal EnableExtensions DisableDelayedExpansion',
    `rem ${SHIM_MARK} - generated by Juanzhi (Settings - Admin - Install command-line tool). Reinstall it if Juanzhi is moved or removed.`,
    'for /f "tokens=2 delims=:." %%a in (\'chcp\') do set "JZ_CP=%%a"',
    'chcp 65001 >nul',
    `set "JZ_EXE=${exe}"`,
    'if not exist "%JZ_EXE%" goto :missing',
    'set "JZ_OUT=%TEMP%\\juanzhi-%RANDOM%%RANDOM%.json"',
    'del "%JZ_OUT%" "%JZ_OUT%.exit" >nul 2>nul',
    'set "JUANZHI_RESULT_FILE=%JZ_OUT%"',
    'start "" /wait "%JZ_EXE%" cli %*',
    'set "JZ_CODE=%ERRORLEVEL%"',
    'if not exist "%JZ_OUT%" goto :noresult',
    'type "%JZ_OUT%"',
    'set "JZ_FILECODE="',
    'if exist "%JZ_OUT%.exit" set /p JZ_FILECODE=<"%JZ_OUT%.exit"',
    'if defined JZ_FILECODE set "JZ_CODE=%JZ_FILECODE%"',
    'del "%JZ_OUT%" "%JZ_OUT%.exit" >nul 2>nul',
    'goto :done',
    ':missing',
    `echo ${shimError('找不到卷知程序，请在卷知里重新点「安装命令行工具」')}`,
    'set "JZ_CODE=1"',
    'goto :done',
    ':noresult',
    `echo ${shimError('卷知没有返回结果（命令没有正常结束）')}`,
    'set "JZ_CODE=1"',
    ':done',
    'if defined JZ_CP chcp %JZ_CP% >nul',
    'endlocal & exit /b %JZ_CODE%',
    ''
  ]
  return lines.join('\r\n')
}

/**
 * 把目录加进「用户级」PATH 的 PowerShell 脚本：直接读写注册表 HKCU\Environment\Path，原样保留类型（REG_EXPAND_SZ）和里面的 %变量%（不展开），只在末尾追加；
 * 追加前把原值备份到 JZ_BACKUP_FILE（出问题可以恢复）；写完广播 WM_SETTINGCHANGE，新开的终端立刻生效。目录和备份路径从环境变量读，不拼进脚本。
 */
export const WINDOWS_PATH_SCRIPT = [
  "$ErrorActionPreference = 'Stop'",
  '$d = $env:JZ_BIN_DIR; $bk = $env:JZ_BACKUP_FILE',
  "$k = [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $true)",
  'try {',
  "  $has = $k.GetValueNames() -contains 'Path'",
  "  $raw = ''; $kind = [Microsoft.Win32.RegistryValueKind]::ExpandString",
  "  if ($has) { $raw = [string]$k.GetValue('Path', '', [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames); $kind = $k.GetValueKind('Path') }",
  "  $parts = @($raw -split ';' | Where-Object { $_ -ne '' })",
  "  $want = [Environment]::ExpandEnvironmentVariables($d).TrimEnd('\\')",
  "  foreach ($p in $parts) { if ([Environment]::ExpandEnvironmentVariables($p).TrimEnd('\\') -ieq $want) { Write-Output 'already'; exit 0 } }",
  '  New-Item -ItemType Directory -Force (Split-Path -Parent $bk) | Out-Null',
  "  Add-Content -LiteralPath $bk -Value (\"[{0}] kind={1}`r`n{2}`r`n\" -f (Get-Date -Format s), $kind, $raw) -Encoding UTF8",
  "  $new = if ($raw) { $raw.TrimEnd(';') + ';' + $d } else { $d }",
  '  $k.SetValue(\'Path\', $new, $kind)',
  "  Add-Type -Namespace Juanzhi -Name Native -MemberDefinition '[DllImport(\"user32.dll\", SetLastError=true, CharSet=CharSet.Auto)] public static extern IntPtr SendMessageTimeout(IntPtr hWnd, uint Msg, UIntPtr wParam, string lParam, uint fuFlags, uint uTimeout, out UIntPtr lpdwResult);'",
  '  $res = [UIntPtr]::Zero',
  "  [void][Juanzhi.Native]::SendMessageTimeout([IntPtr]0xffff, 0x1A, [UIntPtr]::Zero, 'Environment', 2, 5000, [ref]$res)",
  "  Write-Output 'added'",
  '} finally { $k.Close() }'
].join('\n')

export interface InstallEnv {
  platform: NodeJS.Platform
  home: string
  localAppData?: string
  /** 要执行的程序：安装版 = 当前可执行文件；免安装版 = PORTABLE_EXECUTABLE_FILE */
  exePath: string
  portable: boolean
  /** 允许程序在 /Volumes 下（测试用；正常使用时从 dmg / 外接磁盘里直接运行不允许安装） */
  allowVolumes?: boolean
  /** 运行 PowerShell 脚本（单测里替换）；返回 stdout */
  runPowerShell?: (script: string, env: Record<string, string>) => Promise<string>
  /** 读用户 shell 的 PATH（Mac：从 Dock 启动的程序拿不到用户在 ~/.zshrc 里设的 PATH；单测里替换）；失败返回 null */
  readShellPath?: () => Promise<string | null>
}

export interface InstallResult {
  ok: boolean
  platform: string
  /** 写出的脚本路径 */
  path: string
  /** 脚本所在目录 */
  dir: string
  /** 目录是否已经在 PATH 里（Mac 上是用户 shell 的 PATH；Windows 上是写入用户级 PATH 之后） */
  onPath: boolean
  /** 白话说明：接下来要做什么 */
  hint: string
  warnings: string[]
}

function defaultPowerShell(script: string, env: Record<string, string>): Promise<string> {
  return new Promise((resolve, reject) => {
    const encoded = Buffer.from(script, 'utf16le').toString('base64')
    execFile('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-EncodedCommand', encoded], { env: { ...process.env, ...env }, windowsHide: true, timeout: 30_000 }, (err, stdout, stderr) => {
      if (err) reject(new Error(`${err.message}${stderr ? '：' + String(stderr).trim() : ''}`))
      else resolve(String(stdout).trim())
    })
  })
}

function defaultReadShellPath(): Promise<string | null> {
  return new Promise(resolve => {
    const shell = process.env.SHELL || '/bin/zsh'
    execFile(shell, ['-ilc', 'printf %s "$PATH"'], { timeout: 4000 }, (err, stdout) => resolve(err ? null : String(stdout).trim() || null))
  })
}

/** 当前命令行工具装在哪（不安装，只看；界面显示「已安装」用） */
export function shimPath(env: Pick<InstallEnv, 'platform' | 'home' | 'localAppData'>): { dir: string; file: string } {
  if (env.platform === 'win32') {
    const dir = path.join(env.localAppData || path.join(env.home, 'AppData', 'Local'), 'Juanzhi', 'bin')
    return { dir, file: path.join(dir, 'juanzhi.cmd') }
  }
  const dir = path.join(env.home, '.local', 'bin')
  return { dir, file: path.join(dir, 'juanzhi') }
}

/**
 * 安全地写包装脚本：目标已存在时，符号链接拒绝（不写穿到别处）、不带我们的标记的文件拒绝（不覆盖用户自己的 juanzhi）；其余用临时文件 + 改名原子替换。
 */
export function writeShimSafely(file: string, content: string, mode?: number): void {
  let st: fs.Stats | null = null
  try { st = fs.lstatSync(file) } catch { /* 不存在：直接写 */ }
  if (st) {
    if (st.isSymbolicLink()) throw new Error(`${file} 是一个符号链接，卷知不会覆盖它（会改到它指向的文件）。请先把它改名或删除，再重新安装命令行工具`)
    if (!st.isFile()) throw new Error(`${file} 已经存在而且不是普通文件，卷知不会覆盖它`)
    let old = ''
    try { old = fs.readFileSync(file, 'utf8') } catch { /* 读不了就当不是我们的 */ }
    if (!old.includes('JUANZHI-SHIM')) throw new Error(`已经有一个不是卷知生成的 ${path.basename(file)}（${file}），卷知不会覆盖它。请先把它改名或删除，再重新安装命令行工具`)
  }
  const tmp = `${file}.${process.pid}.tmp`
  try {
    fs.writeFileSync(tmp, content, mode === undefined ? 'utf8' : { encoding: 'utf8', mode })
    if (mode !== undefined) fs.chmodSync(tmp, mode)
    fs.renameSync(tmp, file)
  } catch (e) { try { fs.unlinkSync(tmp) } catch { /* 忽略 */ } throw e }
}

export async function installCliShim(env: InstallEnv, currentPath: string = process.env.PATH ?? ''): Promise<InstallResult> {
  const { dir, file } = shimPath(env)
  const warnings: string[] = []
  if (env.platform === 'darwin' && !env.allowVolumes && /^\/Volumes\//.test(env.exePath)) {
    throw new Error('卷知现在是从安装盘（dmg）或外接磁盘里直接运行的，请先把它拖进「应用程序」文件夹，再从那里打开并安装命令行工具')
  }
  if (env.platform === 'darwin' && /\/AppTranslocation\//.test(env.exePath)) {
    throw new Error('卷知现在是从「下载」文件夹里直接打开的（macOS 把它放在一个临时的只读位置运行，重启后路径就变了）。请先把它拖进「应用程序」文件夹，再从那里打开并安装命令行工具')
  }
  if (env.platform !== 'darwin' && env.platform !== 'win32') throw new Error('命令行工具目前只支持 Mac 和 Windows')
  fs.mkdirSync(dir, { recursive: true })
  if (env.platform === 'win32') {
    writeShimSafely(file, buildCmdShim(env.exePath))
    let added = false
    try {
      const out = await (env.runPowerShell ?? defaultPowerShell)(WINDOWS_PATH_SCRIPT, { JZ_BIN_DIR: dir, JZ_BACKUP_FILE: path.join(path.dirname(dir), 'path-backup.txt') })
      added = /added|already/.test(out)
    } catch (e) { warnings.push(`没能把 ${dir} 加进用户 PATH：${(e as Error).message}。请手动把这个目录加进 PATH，或直接用完整路径运行 ${file}`) }
    if (env.portable) warnings.push('免安装版的限制：短命令指向免安装版文件本身（移动或删除它会失效）；每次运行都要先解压，慢几秒；它的外层启动器不一定传递退出码（命令行会把退出码也写进结果文件，短命令以它为准）。长期给 Agent 用建议装安装版。')
    return { ok: true, platform: 'win32', path: file, dir, onPath: added, warnings,
      hint: `已写入 ${file}${added ? '，并加进了你的用户 PATH（原来的 PATH 已备份到 ' + path.join(path.dirname(dir), 'path-backup.txt') + '）。重新打开 PowerShell / 命令提示符后，就可以直接输入 juanzhi status' : '。请把这个目录加进 PATH，或用完整路径运行'}` }
  }
  writeShimSafely(file, buildShellShim(env.exePath), 0o755)
  // 从 Dock 启动的程序拿到的 PATH 通常只有系统目录，看不出用户有没有在 ~/.zshrc 里加过：问一下用户的登录 shell
  const shellPath = await (env.readShellPath ?? defaultReadShellPath)().catch(() => null)
  const seen = shellPath ?? currentPath
  const onPath = seen.split(':').some(p => p && path.resolve(p) === path.resolve(dir))
  return { ok: true, platform: 'darwin', path: file, dir, onPath, warnings,
    hint: onPath
      ? `已写入 ${file}，${dir} 已经在你的 PATH 里，重新打开终端后可以直接输入 juanzhi status`
      : `已写入 ${file}。如果输入 juanzhi 提示找不到命令，需要把 ${dir} 加进 PATH：在终端里运行 echo 'export PATH="$HOME/.local/bin:$PATH"' >> ~/.zshrc，然后重新打开终端（如果你已经加过这一行，可以忽略）` }
}
